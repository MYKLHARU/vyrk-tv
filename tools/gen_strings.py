#!/usr/bin/env python3
"""Generate Android string resources from i18n/<lang>.json.

- Writes only strings the Kotlin code uses (R.string.<key>).
- Fails if any language misses a used key, or if a translation's %1$s / %1$d placeholders
  differ from English.
- app_name is injected by Gradle (resValue), so it is never written here.

Usage: python tools/gen_strings.py [--check]
"""
import json
import re
import sys
from pathlib import Path
from xml.sax.saxutils import escape

ROOT = Path(__file__).resolve().parent.parent
SRC = ROOT / "app" / "src" / "main" / "java"
RES = ROOT / "app" / "src" / "main" / "res"
I18N = ROOT / "i18n"
LANGS = {"en": "values", "es": "values-es", "pt-BR": "values-pt-rBR", "fr": "values-fr", "de": "values-de", "hi": "values-hi", "it": "values-it"}
PLACEHOLDER = re.compile(r"%(\d+)\$([sd])")


def used_keys() -> set:
    keys = set()
    for f in SRC.rglob("*.kt"):
        keys.update(re.findall(r"R\.string\.([a-z0-9_]+)", f.read_text(encoding="utf-8")))
    keys.discard("app_name")
    return keys


def android_escape(s: str) -> str:
    s = escape(s)
    s = s.replace("\\", "\\\\").replace("'", "\\'").replace('"', '\\"')
    if s.startswith("@") or s.startswith("?"):
        s = "\\" + s
    return s.replace("\n", "\\n")


def main() -> int:
    check_only = "--check" in sys.argv
    if "--only" in sys.argv:
        only = sys.argv[sys.argv.index("--only") + 1]
        for k in list(LANGS):
            if k != only:
                del LANGS[k]
    keys = used_keys()
    base = json.loads((I18N / "en.json").read_text(encoding="utf-8"))
    errors = []
    tables = {}
    for lang in LANGS:
        path = I18N / f"{lang}.json"
        if not path.exists():
            errors.append(f"{lang}: missing file {path.name}")
            continue
        table = json.loads(path.read_text(encoding="utf-8"))
        for k in sorted(keys):
            if k not in table:
                errors.append(f"{lang}: missing key '{k}'")
                continue
            if k in base and sorted(PLACEHOLDER.findall(table[k])) != sorted(PLACEHOLDER.findall(base[k])):
                errors.append(f"{lang}: placeholder mismatch in '{k}': {table[k]!r} vs {base[k]!r}")
        tables[lang] = table
    if errors:
        print("\n".join(errors), file=sys.stderr)
        return 1
    if check_only:
        print(f"OK: {len(keys)} keys in {len(LANGS)} languages")
        return 0
    for lang, folder in LANGS.items():
        out = RES / folder
        out.mkdir(parents=True, exist_ok=True)
        lines = ['<?xml version="1.0" encoding="utf-8"?>', "<!-- Generated by tools/gen_strings.py from i18n/. Do not edit. -->", "<resources>"]
        for k in sorted(keys):
            fmt = ' formatted="false"' if "%" in tables[lang][k] and not PLACEHOLDER.search(tables[lang][k]) else ""
            lines.append(f'    <string name="{k}"{fmt}>{android_escape(tables[lang][k])}</string>')
        lines.append("</resources>")
        (out / "strings.xml").write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"Wrote {len(keys)} strings for {len(LANGS)} languages")
    return 0


if __name__ == "__main__":
    sys.exit(main())
