package com.vyrk.tv.ui.components

import android.content.Context
import java.time.LocalDate

/**
 * What the opening needs to remember between launches: the title Home featured last (its id and
 * backdrop, which the V opens onto and Home starts on), and the day the full opening last played.
 */
object IntroPrefs {
    private const val FILE = "vyrk_intro"

    /** The remembered featured title: its id, its artwork key (as the wallpaper uses) and its backdrop. */
    data class Featured(val id: String, val key: String, val backdrop: String)

    fun featured(context: Context): Featured? {
        val p = context.getSharedPreferences(FILE, Context.MODE_PRIVATE)
        val id = p.getString("featured_id", null) ?: return null
        val key = p.getString("featured_key", null) ?: return null
        val url = p.getString("featured_backdrop", null) ?: return null
        return Featured(id, key, url)
    }

    /** Home calls this whenever its featured title changes. */
    fun setFeatured(context: Context, id: String, key: String, backdrop: String) {
        if (featured(context) == Featured(id, key, backdrop)) return
        context.getSharedPreferences(FILE, Context.MODE_PRIVATE).edit()
            .putString("featured_id", id).putString("featured_key", key).putString("featured_backdrop", backdrop).apply()
    }

    /** [candidates] with the remembered featured title first, so Home opens on what the V showed. */
    fun <T> preferFeatured(context: Context, candidates: List<T>, id: (T) -> String): List<T> {
        val saved = featured(context)?.id ?: return candidates
        val i = candidates.indexOfFirst { id(it) == saved }
        return if (i <= 0) candidates else listOf(candidates[i]) + candidates.filterIndexed { j, _ -> j != i }
    }

    /** Reduce motion and the opening sound, copied here so the opening can decide before the app's settings load. */
    fun mirror(context: Context, reduceMotion: Boolean, sound: Boolean) {
        val p = context.getSharedPreferences(FILE, Context.MODE_PRIVATE)
        if (p.getBoolean("reduce_motion", false) == reduceMotion && p.getBoolean("sound", true) == sound) return
        p.edit().putBoolean("reduce_motion", reduceMotion).putBoolean("sound", sound).apply()
    }

    fun reduceMotion(context: Context) = context.getSharedPreferences(FILE, Context.MODE_PRIVATE).getBoolean("reduce_motion", false)
    fun sound(context: Context) = context.getSharedPreferences(FILE, Context.MODE_PRIVATE).getBoolean("sound", true)

    /** True the first time it's asked on a given day (and remembers that it was). */
    fun firstLaunchToday(context: Context): Boolean {
        val p = context.getSharedPreferences(FILE, Context.MODE_PRIVATE)
        val today = LocalDate.now().toString()
        if (p.getString("full_day", null) == today) return false
        p.edit().putString("full_day", today).apply()
        return true
    }
}

/**
 * VYRK's opening, laid over the app as it starts. It's an animated vector (res/drawable/intro_full,
 * intro_sting; generated by tools/gen_intro.py), which Android animates on its render thread, so it
 * stays smooth while the app is busy starting underneath. The full version (about 3.7 s, with its
 * sound) plays on the first launch of the day: gold hairlines draw a ring, the Elder Futhark is
 * inscribed round it, the two blades of the V slide in and lock with a strike, a glint runs round the
 * runes and VYRK is drawn beneath; then the V becomes a window onto Home and the camera dives through.
 * Later launches get a 1-second sting of the V alone. Skipped with Reduce motion, and when Android's
 * own animations are off.
 */
object LaunchIntro {
    private var played = false

    fun play(activity: android.app.Activity, phone: Boolean) {
        if (played || reduceMotionOff(activity) || !systemAnimationsOn(activity)) return
        played = true
        val full = IntroPrefs.firstLaunchToday(activity)
        val avd = activity.getDrawable(if (full) com.vyrk.tv.R.drawable.intro_full else com.vyrk.tv.R.drawable.intro_sting)
            as? android.graphics.drawable.AnimatedVectorDrawable ?: return
        val view = android.widget.ImageView(activity).apply {
            setImageDrawable(avd)
            scaleType = android.widget.ImageView.ScaleType.CENTER_CROP
            isFocusable = false
            importantForAccessibility = android.view.View.IMPORTANT_FOR_ACCESSIBILITY_NO
        }
        activity.addContentView(view, android.view.ViewGroup.LayoutParams(android.view.ViewGroup.LayoutParams.MATCH_PARENT, android.view.ViewGroup.LayoutParams.MATCH_PARENT))
        fun remove() { (view.parent as? android.view.ViewGroup)?.removeView(view) }
        avd.registerAnimationCallback(object : android.graphics.drawable.Animatable2.AnimationCallback() {
            override fun onAnimationEnd(drawable: android.graphics.drawable.Drawable?) { view.post { remove() } }
        })
        // Never leave it up, whatever happens to the animation.
        view.postDelayed({ remove() }, if (full) 5_000L else 2_500L)
        view.post { avd.start() }
        if (!phone && IntroPrefs.sound(activity)) {
            val app = activity.applicationContext
            Thread {
                runCatching {
                    android.media.MediaPlayer.create(app, if (full) com.vyrk.tv.R.raw.intro else com.vyrk.tv.R.raw.intro_sting)?.apply {
                        setVolume(0.8f, 0.8f); setOnCompletionListener { it.release() }; start()
                    }
                }
            }.start()
        }
    }

    private fun reduceMotionOff(context: Context) = IntroPrefs.reduceMotion(context)

    /** Android's own "Remove animations" (Accessibility) or animator scale off (Developer options). */
    private fun systemAnimationsOn(context: Context): Boolean = runCatching {
        android.provider.Settings.Global.getFloat(context.contentResolver, android.provider.Settings.Global.ANIMATOR_DURATION_SCALE, 1f) != 0f
    }.getOrDefault(true)
}
